# ---------------------------------------------------------------------------------------
# 1. source of truth: the generator's own add() calls
# ---------------------------------------------------------------------------------------
def source_components():
    """{ref: (value, footprint, {pin: net})} straight out of gen_base_station_netlist.py."""
    tree = ast.parse(GENERATOR.read_text())
    comps = {}
    for node in ast.walk(tree):
        if (isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
                and node.func.id == "add"):
            ref = ast.literal_eval(node.args[0])
            value = ast.literal_eval(node.args[1])
            fp = ast.literal_eval(node.args[2])
            pins = dict(ast.literal_eval(node.args[3]))
            assert ref not in comps, f"duplicate ref {ref}"
            comps[ref] = (value, fp, pins)
    assert comps, "no components found -- the generator's call shape changed"
    return comps


# ---------------------------------------------------------------------------------------
# 2. S-expression reader for the stock KiCad libraries
# ---------------------------------------------------------------------------------------
def parse_sexpr(text):
    tokens = iter(re.findall(r'"(?:\\.|[^"\\])*"|[^\s()]+|[()]', text))

    def item(tok):
        if tok != "(":
            return tok
        out = []
        for tok in tokens:
            if tok == ")":
                return out
            out.append(item(tok))
        raise ValueError("unclosed expression")

    return item(next(tokens))


def kids(node, key):
    return [v for v in node if isinstance(v, list) and v and v[0] == key]


def one(node, key):
    found = kids(node, key)
    return found[0] if found else None


def unq(s):
    return json.loads(s)


def dump(node):
    return "(" + " ".join(dump(v) for v in node) + ")" if isinstance(node, list) else str(node)


def stock_symbol(lib, name):
    """A stock symbol with `extends` inheritance flattened, as KiCad does on load."""
    path = STOCK / f"{lib}.kicad_sym"
    tree = parse_sexpr(path.read_text())
    sym = next((s for s in kids(tree, "symbol") if unq(s[1]) == name), None)
    if sym is None:
        raise SystemExit(f"stock symbol {lib}:{name} not found in {path}")
    parent = one(sym, "extends")
    if parent:
        base = stock_symbol(lib, unq(parent[1]))
        for flag in ("pin_names", "pin_numbers", "exclude_from_sim", "in_bom", "on_board"):
            if not kids(sym, flag):
                sym.extend(kids(base, flag))
        for sub in kids(base, "symbol"):
            sub[1] = json.dumps(unq(sub[1]).replace(unq(base[1]), name, 1))
            sym.append(sub)
        sym.remove(parent)
    return sym


