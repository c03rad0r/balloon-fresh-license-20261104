def resolve(ref):
    for pattern, spec in MAPPING:
        if re.match(pattern, ref):
            return spec
    raise SystemExit(f"ref {ref} has no symbol mapping -- add a pattern to MAPPING")


# Pads that exist on a LOCAL symbol but that the generator deliberately does not connect.
# Each is a RECORDED open item, not a silent allowance: the parity gate treats these pins as
# "no net" on the native side, so a pin that gains a net still fails parity.
LOCAL_PIN_ALLOWANCE = {
    # The 433 MHz BPF part is not selected. Its stock 6-pad land has pads 3-6 whose real
    # function is unknown at this milestone; the generator connects only 1 (in) and 2 (out).
    "BaseStation:SAW_433": {"3", "4", "5", "6"},
}


def local_pins(spec):
    return spec["left"] + spec["right"]


def local_body(name, spec):
    """Rectangle + pins. Pin NUMBERS come from the generator via LOCAL_SYMBOLS."""
    height = max(len(spec["left"]), len(spec["right"]), 2)
    half_h = (height - 1) * 2.54 / 2
    half_w = 10.16
    out = [f'(symbol "{name}_0_1" (rectangle (start {-half_w} {half_h}) '
           f'(end {half_w} {-half_h}) (stroke (width 0.254) (type default)) '
           f'(fill (type background))))']
    out.append(f'(symbol "{name}_1_1"')
    for i, (num, pname, ptype) in enumerate(spec["left"]):
        out.append(f'(pin {ptype} line (at {-half_w - 2.54} {half_h - i * 2.54} 0) '
                   f'(length 2.54) (name "{pname}" (effects (font (size 1.27 1.27)))) '
                   f'(number "{num}" (effects (font (size 1.27 1.27)))))')
    for i, (num, pname, ptype) in enumerate(spec["right"]):
        out.append(f'(pin {ptype} line (at {half_w + 2.54} {half_h - i * 2.54} 180) '
                   f'(length 2.54) (name "{pname}" (effects (font (size 1.27 1.27)))) '
                   f'(number "{num}" (effects (font (size 1.27 1.27)))))')
    out.append(")")
    return " ".join(out)


def local_def(libid, spec, name):
    return (f'(symbol "{libid}" (exclude_from_sim no) (in_bom yes) (on_board yes) '
            f'(property "Reference" "U" (at 0 0 0) (effects (font (size 1.27 1.27)))) '
            f'(property "Value" "{spec["value"]}" (at 0 0 0) '
            f'(effects (font (size 1.27 1.27)))) '
            f'(property "Footprint" "" (at 0 0 0) (effects (font (size 1.27 1.27)) (hide yes))) '
            f'(property "Datasheet" "" (at 0 0 0) (effects (font (size 1.27 1.27)) (hide yes))) '
            f'(property "Description" "LOCAL SYMBOL: pin numbers copied from '
            f'gen_base_station_netlist.py, NOT verified against a datasheet" '
            f'(at 0 0 0) (effects (font (size 1.27 1.27)) (hide yes))) '
            + local_body(name, spec) + ")")


def uid(s):
    return str(uuid.uuid5(uuid.NAMESPACE_URL, "base-station/" + s))


def snap(v):
    return round(round(v / GRID) * GRID, 4)


def pin_geometry(libdef_text):
    """{number: (x, y, electrical_type)} in symbol coordinates, from the emitted libdef."""
    root = parse_sexpr(libdef_text)
    out = {}
    for unit in kids(root, "symbol"):
        for pin in kids(unit, "pin"):
            at = one(pin, "at")
            out[unq(one(pin, "number")[1])] = (float(at[1]), float(at[2]), pin[1])
    return out


def pin_orientation(libdef_text):
    """{number: angle} for a symbol: 0 = leaves left, 90 = leaves bottom,
    180 = leaves right, 270 = leaves top (KiCad's pin `at` convention)."""
    root = parse_sexpr(libdef_text)
    out = {}
    for unit in kids(root, "symbol"):
        for pin in kids(unit, "pin"):
            at = one(pin, "at")
            out[unq(one(pin, "number")[1])] = int(float(at[3]))
    return out


CHAR_W = 1.15          # mm per character at font size 1.27, with margin
LABEL_H = 2.54


def text_w(s):
    return len(s) * CHAR_W


CAP_ROW = 2.54          # vertical room reserved for a caption line
CAP_GAP = 1.60          # clearance between a caption and the nearest label band


def placement_cell(geom, value, ref, pins, orient):
    """(width, height, x_off, y_off, ext_x, ext_y, up_ext, down_ext) for one part.

    A shelf-packed schematic is only reviewable if each cell reserves the space the TEXT
    needs, not just the symbol body. The vertical order inside a cell is fixed:

        caption row | gap | UP label band | body | DOWN label band | gap | caption row

    Reference sits in the top caption row, Value in the bottom one, so neither can land in
    a label band no matter how long the net name is. Sizing on the body alone produced a
    sheet where every MPN ran into the next part; verify_label_layout.py measures the result.
    """
    ext_x = max(abs(v[0]) for v in geom.values())
    ext_y = max(abs(v[1]) for v in geom.values())
    left_text = max([text_w(pins.get(n) or "") for n, v in geom.items() if v[0] < 0] or [0])
    right_text = max([text_w(pins.get(n) or "") for n, v in geom.items() if v[0] > 0] or [0])
    # Symbol coords have Y up, so a pin with v[1] > 0 sits on the TOP edge and its label
    # grows upward. A pin at v[1] == 0 on a single-pin part (test point) has no edge to
    # hang from, so it is treated as top too -- growing it down would run into the value
    # caption, and growing it up is how the part is drawn in a real schematic.
    up_labels = max([text_w(pins.get(n) or "") for n, v in geom.items()
                     if v[1] >= 0 and orient[n] in (90, 270)] or [0])
    down_labels = max([text_w(pins.get(n) or "") for n, v in geom.items()
                       if v[1] < 0 and orient[n] in (90, 270)] or [0])
    up_ext = up_labels + 1.27 if up_labels else 0.0
    down_ext = down_labels + 1.27 if down_labels else 0.0
    caption = max(text_w(ref), text_w(value))
    x_off = max(ext_x + left_text + 3.81, caption / 2 + 1.27)
    right = max(ext_x + right_text + 3.81, caption / 2 + 1.27)
    y_off = CAP_ROW + CAP_GAP + up_ext + ext_y
    height = y_off + ext_y + down_ext + CAP_GAP + CAP_ROW
    return (x_off + right, height, x_off, y_off, ext_x, ext_y, up_ext, down_ext)


def main():
    comps = source_components()
    provenance: dict[str, str] = {}
    libdefs = {}
    decisions = {}

    # ---- resolve every ref, build library definitions --------------------------------
    for ref in sorted(comps):
        value, fp, pins = comps[ref]
        kind, lib, name, why = resolve(ref)
        status = "stock-verified-pin-set"
        if kind == "local":
            # local tuples are (kind, symbol-name, status, why)
            name, status, lib = lib, name, LOCAL_LIB
        if kind == "stock":
            libid = f"{lib}:{name}"
            libdefs.setdefault(libid, dump(stock_symbol(lib, name)).replace(
                json.dumps(name), json.dumps(libid), 1))
            provenance[f"{lib}.kicad_sym"] = hashlib.sha256(
                (STOCK / f"{lib}.kicad_sym").read_bytes()).hexdigest()
        else:
            libid = f"{LOCAL_LIB}:{name}"
            libdefs.setdefault(libid, local_def(libid, LOCAL_SYMBOLS[name], name))
        decisions[ref] = {"lib_id": libid, "kind": kind, "value": value,
                          "footprint": fp, "rationale": why,
                          "pin_number_basis": status,
                          "symbol_pins": sorted(pin_geometry(libdefs[libid]),
                                                key=lambda n: (len(n), n)),
                          "generator_pins": sorted(pins, key=lambda n: (len(n), n))}

    # ---- pin-set gate ---------------------------------------------------------------
    # STOCK symbols: every pin the generator declares must exist on the symbol with that
    # number. Extra symbol pins are normal (unused RP2040 GPIOs, the LDO's NC pad) and are
    # recorded as unconnected; they cannot invent a net, so they are not a failure.
    # LOCAL symbols: the pin list is authored here from the generator, so it must match
    # exactly -- a local symbol with a pin the generator never mentions would be an
    # invented pin, which is the failure this milestone exists to avoid.
    for ref, d in decisions.items():
        want, got = set(d["generator_pins"]), set(d["symbol_pins"])
        if not want <= got:
            raise SystemExit(f"{ref}: generator pins {sorted(want - got)} are missing from "
                             f"{d['lib_id']} (it has {sorted(got)})")
        extra = got - want
        if d["kind"] == "local" and extra != LOCAL_PIN_ALLOWANCE.get(d["lib_id"], set()):
            raise SystemExit(f"{ref}: local symbol {d['lib_id']} has pins the generator "
                             f"does not declare: {sorted(extra)}")
        d["pins_left_unconnected"] = sorted(extra)

    # ---- local library file ----------------------------------------------------------
    local_used = sorted({d["lib_id"].split(":")[1] for d in decisions.values()
                         if d["kind"] == "local"})
    OUT_LIB.write_text(
        "(kicad_symbol_lib (version 20241209) (generator \"base-station-transcriber\")\n  "
        + "\n  ".join(local_def(f"{LOCAL_LIB}:{n}", LOCAL_SYMBOLS[n], n)
                      for n in local_used) + ")\n")
    provenance["BaseStation.kicad_sym"] = hashlib.sha256(OUT_LIB.read_bytes()).hexdigest()

    # ---- placement: shelf packing sized by the TEXT that must fit around each part ---
    objects, coords, extents = [], {}, {}
    shelf_x, shelf_y, shelf_h = MARGIN, MARGIN, 0.0
    for ref in sorted(comps):
        d = decisions[ref]
        lib_id = d["lib_id"]
        geom = pin_geometry(libdefs[lib_id])
        orient = pin_orientation(libdefs[lib_id])
        (cell_w, cell_h, x_off, y_off, ext_x, ext_y,
         up_ext, down_ext) = placement_cell(geom, d["value"], ref, comps[ref][2], orient)
        if shelf_x + cell_w > SHEET_W - MARGIN:
            shelf_x, shelf_y, shelf_h = MARGIN, shelf_y + shelf_h, 0.0
        x, y = snap(shelf_x + x_off), snap(shelf_y + y_off)
        if shelf_y + cell_h > SHEET_H - MARGIN:
            raise SystemExit(f"layout overflow at {ref}; the sheet needs to be taller")
        shelf_x += cell_w
        shelf_h = max(shelf_h, cell_h)
        coords[ref] = (x, y)
        extents[ref] = (ext_x, ext_y, up_ext, down_ext)
        # Reference in the reserved TOP caption row, Value in the reserved BOTTOM one.
        ref_y = y - ext_y - up_ext - CAP_GAP - CAP_ROW / 2
        val_y = y + ext_y + down_ext + CAP_GAP + CAP_ROW / 2
        objects.append(
            f'(symbol (lib_id "{lib_id}") (at {x} {y} 0) (unit 1) (in_bom yes) '
            f'(on_board yes) (dnp no) (uuid {uid(ref)}) '
            f'(property "Reference" "{ref}" (at {x} {snap(ref_y)} 0) '
            f'(effects (font (size 1.27 1.27)))) '
            f'(property "Value" "{d["value"]}" (at {x} {snap(val_y)} 0) '
            f'(effects (font (size 1.27 1.27)))) '
            f'(property "Footprint" "{d["footprint"]}" (at {x} {y} 0) '
            f'(effects (font (size 1.27 1.27)) (hide yes))) '
            f'(instances (project "base_station_v1" (path "/{ROOT}" '
            f'(reference "{ref}") (unit 1)))))')

    # ---- one label per connected pin, one no-connect per unconnected pin -------------
    nets, pin_types = {}, {}
    pin_positions = {}
    for ref, (value, fp, pins) in comps.items():
        for pin, net in pins.items():
            nets.setdefault(net, set()).add((ref, pin))
    for ref in sorted(comps):
        x, y = coords[ref]
        geom = pin_geometry(libdefs[decisions[ref]["lib_id"]])
        pins = comps[ref][2]
        pin_positions[ref] = {}
        pin_angle = pin_orientation(libdefs[decisions[ref]["lib_id"]])
        # The RP2040 symbol stacks several IOVDD/DVDD pins on ONE coordinate (that is how
        # KiCad models a shared pad group). Emitting a label per pin painted several labels
        # on top of each other. Emit ONE label per unique coordinate instead -- but only
        # after asserting every pin sharing that coordinate is on the same net, because two
        # different nets at one point would be a short, not a labelling problem.
        at_position = {}
        for num, (px, py, ptype) in geom.items():
            key = (snap(x + px), snap(y - py))
            net = pins.get(num)
            at_position.setdefault(key, []).append((num, net, ptype))
            pin_positions[ref][num] = {"x": key[0], "y": key[1], "net": net}
        for (sx, sy), sharing in sorted(at_position.items()):
            nets_here = {n for _num, n, _t in sharing if n is not None}
            if len(nets_here) > 1:
                raise SystemExit(f"{ref}: pins {[s[0] for s in sharing]} share one coordinate "
                                 f"but carry different nets {sorted(nets_here)}")
            net = nets_here.pop() if nets_here else None
            pin_types.setdefault(net, set()).update(t for _n, _x, t in sharing)
            # Label ORIENTATION follows the pin so text runs AWAY from the body and
            # neighbouring labels become parallel columns instead of one pile:
            #   pin out of the left side  -> text to the left,   rotated 0, justify right
            #   pin out of the right side -> text to the right,  rotated 0, justify left
            #   pin out of the top        -> text upward,        rotated 90, justify left
            #   pin out of the bottom     -> text downward,      rotated 90, justify right
            # The top/bottom distinction matters: a 90-degree label grows UP from its anchor
            # either way, so a bottom pin justified "left" climbs straight through the label
            # on the pin above it. Measured: that put GND on top of +3V3_MCU on every
            # two-pin passive on the sheet.
            angle = pin_angle[sharing[0][0]]
            # Direction comes from which EDGE the pin sits on (sign of its symbol-Y), not
            # from comparing the pin to the body centre: a single-pin part like a test point
            # has its pin AT the origin, and testing "is it above the centre" made those
            # labels grow down into their own value caption.
            above = geom[sharing[0][0]][1] >= 0
            if angle in (90, 270):
                rot = 90
                justify = "left" if above else "right"
            elif angle == 0:
                rot, justify = 0, "right"
            else:
                rot, justify = 0, "left"
            if net:
                objects.append(f'(label "{net}" (at {sx} {sy} {rot}) '
                               f'(effects (font (size 1.27 1.27)) '
                               f'(justify {justify} bottom)) '
                               f'(uuid {uid(ref + str(sx) + str(sy) + "L")}))')
            else:
                objects.append(f'(no_connect (at {sx} {sy}) '
                               f'(uuid {uid(ref + str(sx) + str(sy) + "NC")}))')

    # ---- PWR_FLAG for every net with a power_in pin and no power_out -----------------
    flag_nets = sorted(n for n, t in pin_types.items()
                       if "power_in" in t and "power_out" not in t)
    libdefs["power:PWR_FLAG"] = dump(stock_symbol("power", "PWR_FLAG")).replace(
        json.dumps("PWR_FLAG"), json.dumps("power:PWR_FLAG"), 1)
    provenance["power.kicad_sym"] = hashlib.sha256(
        (STOCK / "power.kicad_sym").read_bytes()).hexdigest()
    for i, net in enumerate(flag_nets, 1):
        anchor = min(nets[net])
        ax, ay = coords[anchor[0]]
        fx, fy = snap(ax), snap(ay + 25.4 + 10.16 * i)
        objects.append(
            f'(symbol (lib_id "power:PWR_FLAG") (at {fx} {fy} 0) (unit 1) '
            f'(in_bom no) (on_board no) (dnp no) (uuid {uid("flag" + net)}) '
            f'(property "Reference" "#FLG{i:02d}" (at {fx} {fy - 5.08} 0) '
            f'(effects (font (size 1.27 1.27)) (hide yes))) '
            f'(property "Value" "PWR_FLAG" (at {fx} {fy + 5.08} 0) '
            f'(effects (font (size 1.27 1.27)))) '
            f'(instances (project "base_station_v1" (path "/{ROOT}" '
            f'(reference "#FLG{i:02d}") (unit 1)))))')
        objects.append(f'(label "{net}" (at {fx} {fy} 0) '
                       f'(effects (font (size 1.27 1.27)) (justify left bottom)) '
                       f'(uuid {uid("flaglabel" + net)}))')

    OUT_SCH.write_text(
        f'(kicad_sch (version 20250114) (generator "eeschema") (uuid {ROOT}) '
        f'(paper "A2") (lib_symbols ' + " ".join(libdefs.values()) + ') '
        + " ".join(objects) + ')\n')

    OUT_PRO.write_text(json.dumps({
        "meta": {"filename": "base_station_v1.kicad_pro", "version": 1},
        "board": {}, "libraries": {"pinned_footprint_libs": [],
                                   "pinned_symbol_libs": []},
        "schematic": {"legacy_lib_dir": "", "legacy_lib_list": []},
        "sheets": [],
        "_note": "minimal project: native ERC and netlist export only. No layout in this "
                 "milestone and no PCB is derived from this file yet.",
    }, indent=2) + "\n")
    (HERE / "sym-lib-table").write_text(
        '(sym_lib_table (lib (name "BaseStation")(type "KiCad")'
        '(uri "${KIPRJMOD}/BaseStation.kicad_sym")(options "")(descr '
        '"LOCAL base-station symbols; pin numbers copied from the generator, '
        'not datasheet-verified")))' + "\n")

    OUT_MAP.write_text(json.dumps({
        "_note": "Every ref -> symbol decision. 'stock' symbols were verified pin-set "
                 "exact against the generator. 'local' symbols carry pin numbers copied "
                 "from the generator and are NOT datasheet-verified.",
        "components": dict(sorted(decisions.items())),
        "pwr_flag_nets": flag_nets,
        "pin_positions": pin_positions,
        "nets": {n: sorted(nodes) for n, nodes in sorted(nets.items())},
    }, indent=2) + "\n")
    OUT_HASH.write_text(json.dumps(dict(sorted(provenance.items())), indent=2) + "\n")

    print(f"wrote {OUT_SCH.name}: {len(comps)} components, {len(nets)} nets, "
          f"{len(flag_nets)} PWR_FLAG, {len(objects)} schematic objects")
    print(f"  stock symbols : "
          f"{sorted({d['lib_id'] for d in decisions.values() if d['kind'] == 'stock'})}")
    print(f"  local symbols : {local_used}")
    print(f"  pwr-flag nets : {flag_nets}")


