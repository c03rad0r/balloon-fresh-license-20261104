#!/usr/bin/env python3
"""Transcribe the base-station logical netlist into a loadable native KiCad schematic.

THIS IS A TRANSCRIPTION, NOT A REDESIGN. The component list and every (pin -> net)
assignment are read out of gen_base_station_netlist.py by AST parse of its `add(...)`
calls -- the same source of truth the netlist generator and its tests use. Nothing here
adds, removes or re-names a net or a pin. base_station_parity.py proves that on the
native export.

WHY: the base station's only electrical source of truth was a Python script that emitted a
netlist directly. A netlist cannot be ERC'd or reviewed, so every logical repair (regulator
pinout, 5 V rail, RP2040 pad map, MCU supply) landed in a script that no native tool
consumes. A native .kicad_sch is the artifact native ERC can grade.

SYMBOLS: where a stock KiCad symbol exists whose pin NUMBERS are the pins the generator
declares, that stock symbol is used. Where no stock symbol exists (ADL5240, AD8318, the
433 MHz SAW filter, the unselected load switch) a local symbol is emitted whose pin numbers
are COPIED from the generator's pin list -- never invented -- and every decision lands in
symbol-mapping.json. The local symbols are marked UNVERIFIED: their numbers are the
generator's logical numbers, not a datasheet reading.

OUTPUT (all beside this file):
  base_station_v1.kicad_sch   the native schematic
  base_station_v1.kicad_pro   minimal project so ERC/netlist run headless
  BaseStation.kicad_sym       local symbol library (only parts with no stock symbol)
  sym-lib-table               symbol library table for the local library
  symbol-mapping.json         every ref -> library symbol, and why
  library-sha256.json         provenance hashes of every library file read

The PCB is NOT touched or regenerated by this script.
"""
